"""La Homebrew Store no copia un GXGlobal.cfg de relleno.

USB Loader GX está en Open Shop Channel (slug `usbloader_gx`; verificado
contra la API el 2026-10-18) y su ZIP no trae GXGlobal.cfg. Al instalarlo,
`golden_configs.maybe_apply` copiaba a la unidad del cliente el
`assets/configs/usbloadergx/GXGlobal.cfg` del repositorio, que es un
archivo de relleno (marcado PLACEHOLDER) con comentarios de desarrollo y
valores de prueba.

No hace falta ninguno: USB Loader GX arma el suyo (su código fuente,
release v4.0-r1283: `CSettings::FindConfig` crea el archivo,
`SetDefault` pone `GameCubePath = usb1:/games/` y el resto por defecto, y
`AppCleanUp` lo guarda completo con `Save`). Ahora un archivo maestro
marcado como relleno no se copia y queda una nota en el historial; uno de
verdad se sigue copiando, y una unidad que ya tiene el suyo no se toca
nunca.
"""
from __future__ import annotations

import types
import zipfile
from pathlib import Path

import pytest

from homebrew_falso import dol
from wiibackup_manager import golden_configs, oplog, oscwii_installer
from wiibackup_manager.golden_configs import GoldenConfigSpec, GoldenConfigStatus
from wiibackup_manager.oscwii_client import HomebrewApp
from wiibackup_manager.oscwii_installer import InstallResult, InstallStatus

# Lo que trae el ZIP real de OSC (usbloader_gx 4.0 r1283), sin los .lang.
ZIP_OSC = {
    "apps/usbloader_gx/boot.dol": dol(b"dol"),
    "apps/usbloader_gx/meta.xml": b"<app version='4.0 r1283'/>",
    "apps/usbloader_gx/icon.png": b"png",
    "apps/usbloader_gx/wiitdb.xml": b"<datafile/>",
    "apps/usbloader_gx/language/spanish.lang": b"msgid",
}

# Un GXGlobal.cfg como los que escribe USB Loader GX (`CSettings::Save`).
DE_VERDAD = (b"# USB Loader GX R1283 - Main settings file\n"
             b"# Note: This file is automatically generated\n"
             b"videomode = 1\nGameCubePath = usb1:/games/\n")


def _app() -> HomebrewApp:
    return HomebrewApp(slug="usbloader_gx", name="USB Loader GX",
                       zip_url="https://hbb1.oscwii.org/api/contents/usbloader_gx/"
                               "usbloader_gx.zip")


@pytest.fixture
def historial(tmp_path):
    return oplog.OperationLog(path=tmp_path / "history.json")


@pytest.fixture
def zip_osc(monkeypatch):
    def _fake(app, dest_path, cancel_event, on_progress):
        with zipfile.ZipFile(dest_path, "w") as zf:
            for nombre, datos in ZIP_OSC.items():
                zf.writestr(nombre, datos)
        return True, "", "", ""

    monkeypatch.setattr(oscwii_installer, "_download_zip", _fake)


def _registro_con(tmp_path, monkeypatch, contenido: bytes) -> dict:
    assets = tmp_path / "assets"
    (assets / "usbloadergx").mkdir(parents=True)
    (assets / "usbloadergx" / "GXGlobal.cfg").write_bytes(contenido)
    monkeypatch.setattr(golden_configs, "_candidate_asset_dirs", lambda: [assets])
    spec = golden_configs.GOLDEN_CONFIGS["usbloader_gx"]
    return {"usbloader_gx": GoldenConfigSpec(
        label=spec.label, asset_relative=spec.asset_relative,
        dest_relative=spec.dest_relative, min_size_bytes=spec.min_size_bytes,
        magic=spec.magic)}


def _archivos(raiz: Path) -> dict:
    return {str(p.relative_to(raiz)): p.read_bytes()
            for p in sorted(raiz.rglob("*")) if p.is_file()}


# ------------------------------------------------- El de relleno --
def test_el_gxglobal_del_repositorio_esta_marcado_como_relleno():
    asset = golden_configs.find_asset("usbloadergx/GXGlobal.cfg")

    assert asset is not None
    assert golden_configs.is_placeholder(asset)


@pytest.mark.parametrize("contenido, relleno", [
    (b"# PLACEHOLDER - GXGlobal.cfg de prueba\nvideomode = 1\n", True),
    (DE_VERDAD, False),
    (golden_configs.NIN_CFG_MAGIC + b"\x00" * 544, False),
], ids=["con-marca", "de-verdad", "binario"])
def test_reconoce_el_relleno_por_su_marca(tmp_path, contenido, relleno):
    archivo = tmp_path / "maestro"
    archivo.write_bytes(contenido)

    assert golden_configs.is_placeholder(archivo) is relleno


def test_instalar_usb_loader_gx_no_copia_el_de_relleno(tmp_path, zip_osc, historial):
    """El camino real: el ZIP de OSC y el archivo maestro del repositorio."""
    raiz = tmp_path / "usb"
    raiz.mkdir()

    instalado = oscwii_installer.install_app(_app(), raiz)
    r = golden_configs.maybe_apply(_app(), raiz, instalado, op_log=historial)

    assert instalado.ok, instalado.error
    assert r.status is GoldenConfigStatus.SKIPPED_PLACEHOLDER
    assert not r.applied and not r.status.is_error
    assert not (raiz / "apps" / "usbloader_gx" / "GXGlobal.cfg").exists()
    assert _archivos(raiz) == ZIP_OSC
    [nota] = historial.entries()
    assert nota.operation == golden_configs.KEPT_OPERATION
    assert nota.status == oplog.STATUS_OK and nota.target == "USB Loader GX"
    assert "relleno" in nota.detail


def test_un_maestro_de_verdad_se_sigue_copiando(tmp_path, monkeypatch, historial):
    registro = _registro_con(tmp_path, monkeypatch, DE_VERDAD)
    raiz = tmp_path / "usb"
    (raiz / "apps" / "usbloader_gx").mkdir(parents=True)

    r = golden_configs.maybe_apply(_app(), raiz, InstallResult(InstallStatus.OK, "x"),
                                   op_log=historial, registry=registro)

    assert r.applied
    assert (raiz / "apps" / "usbloader_gx" / "GXGlobal.cfg").read_bytes() == DE_VERDAD


@pytest.mark.parametrize("maestro", [None, DE_VERDAD], ids=["relleno-real", "de-verdad"])
def test_una_unidad_con_su_gxglobal_queda_intacta(tmp_path, monkeypatch, historial,
                                                  maestro):
    registro = (golden_configs.GOLDEN_CONFIGS if maestro is None
                else _registro_con(tmp_path, monkeypatch, maestro))
    raiz = tmp_path / "usb"
    propio = raiz / "apps" / "usbloader_gx" / "GXGlobal.cfg"
    propio.parent.mkdir(parents=True)
    propio.write_bytes(b"# USB Loader GX R1283\nlanguage = 4\n")

    r = golden_configs.maybe_apply(_app(), raiz, InstallResult(InstallStatus.OK, "x"),
                                   op_log=historial, registry=registro)

    assert r.status is GoldenConfigStatus.KEPT_EXISTING
    assert propio.read_bytes() == b"# USB Loader GX R1283\nlanguage = 4\n"


def test_la_tienda_dice_que_arranca_con_la_de_fabrica(tmp_path):
    from wiibackup_manager.operations import OperationManager
    from wiibackup_manager.widgets.homebrew_store_view import HomebrewStoreView

    toasts = []
    vista = types.SimpleNamespace(
        ops=OperationManager(), op_log=None, _show_toast=toasts.append,
        _install_states={}, _card_by_slug={})
    dorado = golden_configs.GoldenConfigResult(
        GoldenConfigStatus.SKIPPED_PLACEHOLDER, "usbloader_gx", "USB Loader GX")

    HomebrewStoreView._on_install_done(
        vista, _app(), InstallResult(InstallStatus.OK, "usbloader_gx"), None, dorado)

    assert toasts[-1] == ("'USB Loader GX' se instaló con su configuración de fábrica: "
                          "la configuración maestra del repositorio es de relleno y no "
                          "se copió.")
